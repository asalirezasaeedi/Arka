#!/usr/bin/env python3
"""DGP++ v3.0 Level-5 single-file data generation engine.

DGP++ is a deterministic, dependency-light synthetic data generator for
multi-manifold, non-stationary research benchmarks.  The public API preserves a
clean MSB/TAE/IGE pipeline while using episode-based Ornstein-Uhlenbeck dynamics,
skew-symmetric theta rotations, active cross-manifold coupling, vectorized Gate-0
metrics, seven use-case adapters, real streaming, split benchmark views, and a
terminal dashboard.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Dict, Iterator, List, Mapping, Optional, Sequence, Tuple

import numpy as np
import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq

__version__ = "3.0.0"
Z_CLIP = 10.0
Array = np.ndarray


@dataclass(frozen=True)
class GeneratorConfig:
    """Configuration for :class:`MultiManifoldGenerator`.

    Args:
        n_samples: Number of observations generated per episode.
        n_features: Number of emitted observed feature columns.
        latent_dim: Latent dimensionality of the OU state.
        manifolds: Number of manifolds/regimes.
        episodes: Number of episodes generated by :meth:`generate`.
        delta_min: Minimum target separation between manifold centers.
        delta_max: Soft maximum separation between manifold centers.
        tau_min: Minimum OU restoring time constant.
        tau_max: Maximum OU restoring time constant.
        horizon_min: Minimum task horizon annotation.
        horizon_max: Maximum task horizon annotation.
        drift_scale: Per-step center random-walk scale.
        shock_rate: Probability of latent shock at each step.
        noise: Observation noise standard deviation.
        coupling: Global multiplier for the coupling matrix.
        theta_scale: Magnitude of skew-symmetric theta rotations.
        seed: Seed for local ``np.random.default_rng``.
    """

    n_samples: int = 240
    n_features: int = 8
    latent_dim: int = 8
    manifolds: int = 3
    episodes: int = 2
    delta_min: float = 0.3
    delta_max: float = 0.9
    tau_min: float = 0.5
    tau_max: float = 2.0
    horizon_min: int = 3
    horizon_max: int = 10
    drift_scale: float = 0.005
    shock_rate: float = 0.25
    noise: float = 0.05
    coupling: float = 1.0
    theta_scale: float = 0.1
    seed: int = 42

    def validate(self) -> None:
        """Validate configuration values.

        Raises:
            ValueError: If a configuration value is outside the supported range.
        """

        if self.n_samples <= 2:
            raise ValueError("n_samples must be greater than 2")
        if self.n_features <= 0 or self.latent_dim <= 1:
            raise ValueError("n_features must be positive and latent_dim must exceed 1")
        if self.manifolds < 2 or self.episodes <= 0:
            raise ValueError("manifolds must be >= 2 and episodes must be positive")
        if not (0.0 < self.delta_min < self.delta_max):
            raise ValueError("expected 0 < delta_min < delta_max")
        if self.tau_min <= 0 or self.tau_max < self.tau_min:
            raise ValueError("invalid tau range")
        if self.horizon_min <= 0 or self.horizon_max < self.horizon_min:
            raise ValueError("invalid horizon range")
        if self.drift_scale < 0 or not (0.0 <= self.shock_rate <= 1.0):
            raise ValueError("invalid drift_scale or shock_rate")
        if self.noise < 0 or self.coupling < 0 or self.theta_scale < 0:
            raise ValueError("noise, coupling, and theta_scale must be non-negative")


@dataclass
class GenerationResult:
    """Generated dataset and benchmark metadata.

    Args:
        frame: Analysis dataframe containing observations and latent metadata.
        blind: Blind split with no labels or latent state.
        semi: Semi-supervised split with safe metadata.
        analysis: Full analysis split, identical to ``frame``.
        latent: Stacked latent path used to generate observations.
        manifold_id: Manifold assignment for each row.
        metrics: Gate-0 metric dictionary.
        verdict: PASS or FAIL.
        config: Generator configuration used for generation.
    """

    frame: pd.DataFrame
    blind: pd.DataFrame
    semi: pd.DataFrame
    analysis: pd.DataFrame
    latent: Array
    manifold_id: Array
    metrics: Dict[str, Any]
    verdict: str
    config: GeneratorConfig


class MultiManifoldGenerator:
    """Core DGP++ engine preserving MSB, TAE, and IGE stages.

    The implementation merges a clean three-stage API with episode-based OU
    dynamics.  ``msb`` initializes separated manifold centers and stable
    skew-symmetric theta matrices. ``tae`` evolves a single latent path through
    OU restoring forces, active coupling, shocks, and drift. ``ige`` emits
    clipped observations from the same latent path, preserving single-path
    generation for auditability.

    Args:
        config: Generator configuration.
    """

    def __init__(self, config: Optional[GeneratorConfig] = None) -> None:
        self.config = config or GeneratorConfig()
        self.config.validate()
        self.rng = np.random.default_rng(self.config.seed)
        self._eye = np.eye(self.config.latent_dim)
        self.centers: Array = np.empty((0, self.config.latent_dim))
        self.taus: Array = np.empty(0)
        self.horizons: Array = np.empty(0, dtype=int)
        self.thetas: Array = np.empty((0, self.config.latent_dim, self.config.latent_dim))
        self.coupling_matrix: Array = np.empty((0, 0))
        proj = self.rng.normal(0.0, 1.0, (self.config.latent_dim, self.config.n_features))
        self.projection = proj / np.maximum(np.linalg.norm(proj, axis=0, keepdims=True), 1e-9)
        self.bias = self.rng.normal(0.0, 0.1, self.config.n_features)

    def _separation(self, a: Array, b: Array) -> float:
        """Compute smooth center separation.

        Args:
            a: First center.
            b: Second center.

        Returns:
            Positive smooth separation score.
        """

        d = float(np.linalg.norm(a - b))
        return (1.0 - math.exp(-(d * d) / 4.0)) + 0.3 * d

    def _enforce_separation(self) -> None:
        """Move centers once toward the requested separation band.

        Returns:
            None.
        """

        c = self.config
        for _ in range(4):
            for i in range(c.manifolds):
                for j in range(i + 1, c.manifolds):
                    sep = self._separation(self.centers[i], self.centers[j])
                    direction = self.centers[i] - self.centers[j]
                    direction = direction / (np.linalg.norm(direction) + 1e-8)
                    if sep < c.delta_min:
                        self.centers[i] += 0.4 * direction
                        self.centers[j] -= 0.4 * direction
                    elif sep > c.delta_max:
                        self.centers[i] -= 0.04 * direction
                        self.centers[j] += 0.04 * direction
            np.clip(self.centers, -5.0, 5.0, out=self.centers)

    def msb(self) -> Dict[str, Array]:
        """Build manifold state bank (MSB).

        Returns:
            Dictionary containing centers, taus, horizons, thetas, and coupling.
        """

        c = self.config
        centers = self.rng.normal(0.0, 1.0, (c.manifolds, c.latent_dim)) * 1.5
        self.centers = np.clip(centers, -5.0, 5.0)
        self._enforce_separation()
        self.taus = self.rng.uniform(c.tau_min, c.tau_max, c.manifolds)
        self.horizons = self.rng.integers(c.horizon_min, c.horizon_max + 1, c.manifolds)
        raw = self.rng.normal(0.0, c.theta_scale, (c.manifolds, c.latent_dim, c.latent_dim))
        self.thetas = raw - np.swapaxes(raw, 1, 2)
        norms = np.linalg.norm(self.thetas, axis=(1, 2))
        for k, norm in enumerate(norms):
            if norm > 1.0:
                self.thetas[k] /= norm
        self.coupling_matrix = self.rng.uniform(0.0, 0.05, (c.manifolds, c.manifolds)) * c.coupling
        np.fill_diagonal(self.coupling_matrix, 0.0)
        return {
            "centers": self.centers.copy(),
            "taus": self.taus.copy(),
            "horizons": self.horizons.copy(),
            "thetas": self.thetas.copy(),
            "coupling": self.coupling_matrix.copy(),
        }

    def _drift_centers(self) -> None:
        """Apply clipped center random-walk drift.

        Returns:
            None.
        """

        step = self.rng.normal(0.0, self.config.drift_scale * math.sqrt(0.1), self.centers.shape)
        self.centers = np.clip(self.centers + step, -5.0, 5.0)

    def _attack(self, step: int) -> Tuple[int, str]:
        """Apply a temporal hazard attack to tau, horizon, or theta.

        Args:
            step: Episode-local time step.

        Returns:
            Tuple of attacked manifold index and attack type; ``(-1, "none")``
            when no attack occurs.
        """

        hazard = 1.0 / (1.0 + math.exp(-(1.5 * math.sin(0.05 * step) - 0.5)))
        hazard = float(np.clip(hazard + self.rng.uniform(-0.05, 0.05), 0.0, 0.5))
        if self.rng.random() >= hazard:
            return -1, "none"
        k = int(self.rng.integers(0, self.config.manifolds))
        attack_type = str(self.rng.choice(np.array(["tau", "horizon", "theta"])))
        if attack_type == "tau":
            self.taus[k] = float(np.clip(self.taus[k] * self.rng.uniform(0.6, 1.8), self.config.tau_min, self.config.tau_max))
        elif attack_type == "horizon":
            self.horizons[k] = int(np.clip(self.horizons[k] + int(self.rng.integers(-2, 3)), self.config.horizon_min, self.config.horizon_max))
        else:
            delta = self.rng.normal(0.0, 0.04, (self.config.latent_dim, self.config.latent_dim))
            theta = self.thetas[k] + delta
            theta = theta - theta.T
            norm = np.linalg.norm(theta)
            self.thetas[k] = theta / norm if norm > 1.0 else theta
        return k, attack_type

    def tae(self, state: Optional[Mapping[str, Array]] = None, *, episode_id: int = 0) -> pd.DataFrame:
        """Run temporal adaptation engine (TAE) for one episode.

        Args:
            state: Optional MSB state. The generator's internal state is used
                when omitted.
            episode_id: Episode identifier stored in the output.

        Returns:
            Dataframe containing the single latent path and manifold metadata.
        """

        if state is not None:
            self.centers = np.array(state["centers"], dtype=float, copy=True)
            self.taus = np.array(state["taus"], dtype=float, copy=True)
            self.horizons = np.array(state["horizons"], dtype=int, copy=True)
            self.thetas = np.array(state["thetas"], dtype=float, copy=True)
            self.coupling_matrix = np.array(state["coupling"], dtype=float, copy=True)
        c = self.config
        z = self.rng.normal(0.0, 0.1, c.latent_dim)
        manifold = int(self.rng.integers(0, c.manifolds))
        records: List[Dict[str, Any]] = []
        for step in range(c.n_samples):
            self._drift_centers()
            attacked, attack_type = self._attack(step)
            if self.rng.random() < 0.025:
                manifold = int(self.rng.integers(0, c.manifolds))
            center = self.centers[manifold].copy()
            tau = float(self.taus[manifold])
            theta = self.thetas[manifold]
            restore = -(z - center) / tau
            rotated_noise = (self._eye + theta) @ self.rng.normal(0.0, 0.1, c.latent_dim)
            coupling = np.zeros(c.latent_dim)
            for j in range(c.manifolds):
                if j != manifold:
                    coupling += self.coupling_matrix[manifold, j] * (self.centers[j] - z)
            z = np.clip(z + 0.1 * (restore + coupling) + rotated_noise, -Z_CLIP, Z_CLIP)
            shock_flag = 0
            if self.rng.random() < c.shock_rate:
                z = np.clip(z + self.rng.normal(0.0, self.rng.uniform(0.5, 1.5), c.latent_dim), -Z_CLIP, Z_CLIP)
                shock_flag = 1
            records.append(
                {
                    "episode_id": episode_id,
                    "time": step,
                    "manifold_id": manifold,
                    "z_true": z.copy(),
                    "tau": tau,
                    "horizon": int(self.horizons[manifold]),
                    "shock_flag": shock_flag,
                    "attack_manifold": attacked,
                    "attack_type": attack_type,
                    "drift_center": center,
                    "all_centers": self.centers.copy().reshape(-1),
                    "theta_trace": float(np.trace(theta @ theta.T)),
                    "coupling_sum": float(self.coupling_matrix[manifold].sum()),
                }
            )
        return pd.DataFrame(records)

    def ige(self, latent_frame: pd.DataFrame) -> pd.DataFrame:
        """Emit observations from the same latent path (IGE).

        Args:
            latent_frame: Dataframe returned by :meth:`tae`.

        Returns:
            Dataframe augmented with ``y_obs`` and feature columns ``x0..``.
        """

        out = latent_frame.copy()
        z = _stack(out, "z_true")
        raw = z @ self.projection + self.bias
        nonlinear = 0.15 * np.sin(raw) + 0.05 * np.tanh(raw) ** 2
        obs = np.clip(raw + nonlinear + self.rng.normal(0.0, self.config.noise, raw.shape), -Z_CLIP, Z_CLIP)
        out["y_obs"] = [row.copy() for row in obs]
        for i in range(self.config.n_features):
            out[f"x{i}"] = obs[:, i]
        return out

    def generate_episode(self, episode_id: int = 0) -> pd.DataFrame:
        """Generate one complete episode through MSB, TAE, and IGE.

        Args:
            episode_id: Episode identifier.

        Returns:
            Full analysis dataframe for one episode.
        """

        state = self.msb()
        return self.ige(self.tae(state, episode_id=episode_id))

    def generate(self, adapter: Optional["BaseAdapter"] = None, dashboard: bool = False) -> GenerationResult:
        """Generate all configured episodes and optional adapter columns.

        Args:
            adapter: Optional use-case adapter.
            dashboard: Whether to render the terminal dashboard.

        Returns:
            Rich generation result with splits, metrics, and verdict.
        """

        frames = [self.generate_episode(ep) for ep in range(self.config.episodes)]
        frame = pd.concat(frames, ignore_index=True)
        latent = _stack(frame, "z_true")
        ids = frame["manifold_id"].to_numpy(dtype=int)
        if adapter is not None:
            frame = adapter.apply(frame, latent, ids, self.rng)
        blind, semi, analysis = split_views(frame)
        metrics = Gate0Validator.evaluate(analysis, self.config)
        verdict = Gate0Validator.verdict(metrics)
        result = GenerationResult(frame, blind, semi, analysis, latent, ids, metrics, verdict, self.config)
        if dashboard:
            TerminalDashboard().render(result, adapter.name if adapter else "core")
        return result

    def stream(self, max_steps: int = -1, adapter: Optional["BaseAdapter"] = None) -> Iterator[Dict[str, Any]]:
        """Yield streaming records one at a time.

        Args:
            max_steps: Number of records to stream; ``-1`` streams forever.
            adapter: Optional adapter applied to single-record frames.

        Yields:
            JSON-serializable record dictionaries.
        """

        state = self.msb()
        produced = 0
        while max_steps < 0 or produced < max_steps:
            episode = self.ige(self.tae(state, episode_id=produced))
            for _, row in episode.iterrows():
                if max_steps >= 0 and produced >= max_steps:
                    break
                record = _row_to_jsonable(row)
                record["stream_id"] = produced
                yield record
                produced += 1


def _stack(df: pd.DataFrame, col: str) -> Array:
    """Stack ndarray/list dataframe cells into a matrix.

    Args:
        df: Source dataframe.
        col: Column containing vectors.

    Returns:
        Two-dimensional numpy array.
    """

    return np.vstack(df[col].apply(lambda x: np.asarray(x, dtype=float)).to_numpy())


def _row_to_jsonable(row: pd.Series) -> Dict[str, Any]:
    """Convert a dataframe row to JSON-safe values.

    Args:
        row: Pandas row.

    Returns:
        JSON-serializable dictionary.
    """

    out: Dict[str, Any] = {}
    for key, value in row.items():
        if isinstance(value, np.ndarray):
            out[key] = value.tolist()
        elif isinstance(value, np.generic):
            out[key] = value.item()
        else:
            out[key] = value
    return out


def split_views(df: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Create blind, semi-supervised, and analysis views.

    Args:
        df: Full analysis dataframe.

    Returns:
        Tuple ``(blind, semi, analysis)``.
    """

    feature_cols = [c for c in df.columns if c.startswith("x")]
    blind = df[["episode_id", "time", "y_obs"] + feature_cols].copy()
    semi_cols = ["episode_id", "time", "manifold_id", "tau", "horizon", "shock_flag", "y_obs"] + feature_cols
    semi = df[[c for c in semi_cols if c in df.columns]].copy()
    return blind, semi, df.copy()


def _to_lists(df: pd.DataFrame) -> pd.DataFrame:
    """Convert ndarray cells to lists before persistence.

    Args:
        df: Source dataframe.

    Returns:
        Copy with JSON/Arrow friendly cells.
    """

    out = df.copy()
    for col in out.columns:
        if out[col].dtype == object:
            out[col] = out[col].apply(lambda x: x.tolist() if isinstance(x, np.ndarray) else x)
    return out


def save_outputs(blind: pd.DataFrame, semi: pd.DataFrame, analysis: pd.DataFrame, output_dir: str, formats: Sequence[str] = ("parquet", "csv")) -> Dict[str, str]:
    """Save all benchmark views in requested formats.

    Args:
        blind: Blind split.
        semi: Semi-supervised split.
        analysis: Full analysis split.
        output_dir: Directory where artifacts are written.
        formats: Iterable containing ``csv`` and/or ``parquet``.

    Returns:
        Mapping from artifact name to path.
    """

    Path(output_dir).mkdir(parents=True, exist_ok=True)
    saved: Dict[str, str] = {}
    stamp = time.strftime("%Y%m%d_%H%M%S")
    for name, data in {"blind": blind, "semi": semi, "analysis": analysis}.items():
        safe = _to_lists(data)
        if "parquet" in formats:
            path = str(Path(output_dir) / f"{name}_{stamp}.parquet")
            pq.write_table(pa.Table.from_pandas(safe), path)
            saved[f"{name}_parquet"] = path
        if "csv" in formats:
            path = str(Path(output_dir) / f"{name}_{stamp}.csv")
            csv_df = safe.copy()
            for col in csv_df.columns:
                if csv_df[col].dtype == object:
                    csv_df[col] = csv_df[col].apply(json.dumps)
            csv_df.to_csv(path, index=False)
            saved[f"{name}_csv"] = path
    return saved


class Gate0Validator:
    """Vectorized Gate-0 validation suite."""

    @staticmethod
    def compute_separation(df: pd.DataFrame, config: GeneratorConfig) -> Dict[str, Any]:
        """Compute separation volatility and violation rate.

        Args:
            df: Analysis dataframe.
            config: Generator configuration.

        Returns:
            Metric dictionary for SV.
        """

        ac = _stack(df, "all_centers")
        centers = ac.reshape(-1, config.manifolds, config.latent_dim)
        pairs = [(i, j) for i in range(config.manifolds) for j in range(i + 1, config.manifolds)]
        dists = np.vstack([np.linalg.norm(centers[:, i, :] - centers[:, j, :], axis=1) for i, j in pairs])
        mean_d = dists.mean(axis=0)
        min_d = dists.min(axis=0)
        sv = float(np.std(mean_d) / (np.mean(mean_d) + 1e-8))
        violation = float((min_d < config.delta_min).mean())
        return {"SV": round(sv, 4), "mean_separation": round(float(mean_d.mean()), 4), "violation_rate": round(violation, 4), "SV_pass": sv <= 0.15 and violation <= 0.05}

    @staticmethod
    def compute_drift(df: pd.DataFrame, config: GeneratorConfig) -> Dict[str, Any]:
        """Compute drift direction coherence and velocity.

        Args:
            df: Analysis dataframe.
            config: Generator configuration.

        Returns:
            Metric dictionary for DDC.
        """

        cosines: List[float] = []
        velocities: List[float] = []
        for k in range(config.manifolds):
            sub = df[df["manifold_id"] == k].sort_values(["episode_id", "time"])
            if len(sub) < 3:
                continue
            seq = _stack(sub, "drift_center")
            delta = np.diff(seq, axis=0)
            norms = np.linalg.norm(delta, axis=1, keepdims=True) + 1e-8
            dirs = delta / norms
            velocities.append(float(norms.mean()))
            if len(dirs) > 1:
                cosines.append(float(np.einsum("ij,ij->i", dirs[:-1], dirs[1:]).mean()))
        raw_ddc = float(np.mean(cosines)) if cosines else 0.0
        ddc = (raw_ddc + 1.0) / 2.0
        velocity = float(np.mean(velocities)) if velocities else 0.0
        return {"DDC": round(ddc, 4), "raw_ddc": round(raw_ddc, 4), "mean_velocity": round(velocity, 4), "DDC_pass": ddc >= 0.35 and velocity <= 0.10}

    @staticmethod
    def compute_aes(df: pd.DataFrame) -> Dict[str, Any]:
        """Compute attack effect score from shock and non-shock errors.

        Args:
            df: Analysis dataframe.

        Returns:
            Metric dictionary for AES.
        """

        y = _stack(df, "y_obs")
        z = _stack(df, "z_true")[:, : y.shape[1]]
        err = np.linalg.norm(y - z, axis=1)
        shock = df["shock_flag"].to_numpy(dtype=int) == 1
        attack_ratio = float(shock.mean())
        shock_err = float(err[shock].mean()) if shock.any() else 0.0
        normal_err = float(err[~shock].mean()) if (~shock).any() else 0.0
        aes = shock_err / (normal_err + 1e-8)
        return {"AES": round(float(min(10.0, aes)), 4), "attack_ratio": round(attack_ratio, 4), "mean_err_shock": round(shock_err, 4), "mean_err_normal": round(normal_err, 4), "AES_pass": 0.10 <= attack_ratio <= 0.60}

    @staticmethod
    def compute_diversity(df: pd.DataFrame, config: GeneratorConfig) -> Dict[str, Any]:
        """Compute normalized Shannon diversity index.

        Args:
            df: Analysis dataframe.
            config: Generator configuration.

        Returns:
            Metric dictionary for DI.
        """

        counts = df["manifold_id"].value_counts()
        probs = np.array([counts.get(k, 0) for k in range(config.manifolds)], dtype=float)
        probs = probs / (probs.sum() + 1e-10)
        entropy = float(-np.sum(probs * np.log(probs + 1e-10)))
        di = entropy / math.log(config.manifolds)
        return {"DI": round(di, 4), "entropy": round(entropy, 4), "manifold_counts": {str(k): int(counts.get(k, 0)) for k in range(config.manifolds)}, "DI_pass": di >= 0.35}

    @staticmethod
    def compute_tpi(df: pd.DataFrame) -> Dict[str, Any]:
        """Compute temporal predictability from lag-one autocorrelation.

        Args:
            df: Analysis dataframe.

        Returns:
            Metric dictionary for TPI.
        """

        values: List[float] = []
        for ep in sorted(df["episode_id"].unique()):
            sub = df[df["episode_id"] == ep].sort_values("time")
            y = _stack(sub, "y_obs").mean(axis=1)
            if len(y) > 2 and float(np.std(y)) > 1e-9:
                corr = float(np.corrcoef(y[:-1], y[1:])[0, 1])
                if not math.isnan(corr):
                    values.append(abs(corr))
        tpi = float(np.mean(values)) if values else 0.0
        return {"TPI": round(tpi, 4), "lag1_abs_autocorr": round(tpi, 4), "TPI_pass": tpi >= 0.20}

    @staticmethod
    def evaluate(df: pd.DataFrame, config: GeneratorConfig) -> Dict[str, Any]:
        """Evaluate all Gate-0 metrics.

        Args:
            df: Analysis dataframe.
            config: Generator configuration.

        Returns:
            Combined metric dictionary.
        """

        metrics: Dict[str, Any] = {}
        metrics.update(Gate0Validator.compute_separation(df, config))
        metrics.update(Gate0Validator.compute_drift(df, config))
        metrics.update(Gate0Validator.compute_aes(df))
        metrics.update(Gate0Validator.compute_diversity(df, config))
        metrics.update(Gate0Validator.compute_tpi(df))
        return metrics

    @staticmethod
    def verdict(metrics: Mapping[str, Any]) -> str:
        """Return PASS when all metric pass flags are true.

        Args:
            metrics: Metric dictionary from :meth:`evaluate`.

        Returns:
            ``PASS`` or ``FAIL``.
        """

        flags = [bool(metrics.get(key, False)) for key in ["SV_pass", "DDC_pass", "AES_pass", "DI_pass", "TPI_pass"]]
        return "PASS" if all(flags) else "FAIL"


class BaseAdapter:
    """Base class for use-case adapters."""

    name = "base"
    version = "1.0.0"
    schema: Dict[str, str] = {}

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Apply adapter-specific annotations.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Augmented dataframe.
        """

        return frame.copy()

    def validate_output(self, frame: pd.DataFrame) -> bool:
        """Validate adapter output columns.

        Args:
            frame: Candidate dataframe.

        Returns:
            True when all schema columns are present.
        """

        return all(col in frame.columns for col in self.schema)

    def describe(self) -> str:
        """Describe the adapter.

        Returns:
            Human-readable adapter description.
        """

        return self.__doc__ or self.name


class AnomalyAdapter(BaseAdapter):
    """UC1 anomaly benchmark with point, contextual, and collective anomalies."""

    name = "anomaly"
    schema = {"is_anomaly": "int", "anomaly_type": "str"}

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Inject three deterministic anomaly families.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Dataframe with anomaly labels.
        """

        out = frame.copy()
        n = len(out)
        cols = [c for c in out.columns if c.startswith("x")]
        out["is_anomaly"] = 0
        out["anomaly_type"] = "normal"
        k_each = max(1, n // 60)
        point = rng.choice(n, k_each, replace=False)
        out.loc[point, cols] += rng.normal(4.0, 0.5, (k_each, len(cols)))
        out.loc[point, ["is_anomaly", "anomaly_type"]] = [1, "point"]
        remaining = np.setdiff1d(np.arange(n), point)
        contextual = rng.choice(remaining, k_each, replace=False)
        out.loc[contextual, cols[: max(1, len(cols) // 2)]] *= -1.5
        out.loc[contextual, ["is_anomaly", "anomaly_type"]] = [1, "contextual"]
        start = int(rng.integers(0, max(1, n - k_each)))
        collective = np.arange(start, min(n, start + k_each))
        out.loc[collective, cols] += np.linspace(0.0, 3.0, len(collective))[:, None]
        out.loc[collective, ["is_anomaly", "anomaly_type"]] = [1, "collective"]
        return out


class DriftAdapter(BaseAdapter):
    """UC2 concept drift benchmark with regime annotations."""

    name = "drift"
    schema = {"regime": "int", "drift_score": "float"}

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Add three regimes and smooth drift score.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Dataframe with drift metadata.
        """

        out = frame.copy()
        n = len(out)
        cols = [c for c in out.columns if c.startswith("x")]
        regime = np.minimum(2, (np.arange(n) * 3) // max(1, n))
        out["regime"] = regime
        out["drift_score"] = np.linspace(0.0, 1.0, n)
        out.loc[regime == 1, cols] *= 1.15
        out.loc[regime == 2, cols] += 0.5
        return out


class CausalDataset(BaseAdapter):
    """UC3 causal dataset with confounding, propensity, CATE, and outcome."""

    name = "causal"
    schema = {"treatment": "int", "propensity": "float", "cate": "float", "outcome": "float"}

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Generate confounded treatment assignment and heterogeneous effects.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Dataframe with causal columns.
        """

        out = frame.copy()
        x0 = out["x0"].to_numpy(dtype=float)
        x1 = out["x1"].to_numpy(dtype=float) if "x1" in out else np.zeros(len(out))
        logits = 0.6 * x0 - 0.25 * x1 + 0.35 * (ids - ids.mean())
        propensity = np.clip(1.0 / (1.0 + np.exp(-logits)), 0.05, 0.95)
        treatment = (rng.random(len(out)) < propensity).astype(int)
        cate = np.clip(1.0 + 0.3 * np.tanh(x0) + 0.15 * ids, 0.2, 3.0)
        baseline = 0.4 * x0 + 0.2 * x1 + 0.1 * ids
        out["propensity"] = propensity
        out["treatment"] = treatment
        out["cate"] = cate
        out["outcome"] = baseline + cate * treatment + rng.normal(0.0, 0.1, len(out))
        out["true_ate"] = float(cate.mean())
        return out


CausalAdapter = CausalDataset


class FederatedDataset(BaseAdapter):
    """UC4 federated dataset using Dirichlet non-IID client partitions."""

    name = "federated"
    schema = {"client_id": "int", "client_weight": "float"}

    def __init__(self, clients: int = 5, alpha: float = 0.5) -> None:
        """Initialize federated adapter.

        Args:
            clients: Number of clients.
            alpha: Dirichlet concentration parameter.
        """

        self.clients = clients
        self.alpha = alpha
        self.last_client_distribution: Optional[Array] = None

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Assign rows to clients using a Dirichlet distribution.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Dataframe with client assignments.
        """

        out = frame.copy()
        probs = rng.dirichlet(np.full(self.clients, self.alpha))
        self.last_client_distribution = probs
        clients = rng.choice(np.arange(self.clients), size=len(out), p=probs)
        out["client_id"] = clients
        out["client_weight"] = probs[clients]
        return out


FederatedAdapter = FederatedDataset


class ManifoldEnv(BaseAdapter):
    """UC5 gym-like offline RL transition dataset."""

    name = "rl"
    schema = {"action": "int", "reward": "float", "done": "int"}

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Create actions, rewards, done flags, and next-state features.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Dataframe with RL transition columns.
        """

        out = frame.copy()
        actions = rng.integers(0, 4, len(out))
        out["action"] = actions
        out["reward"] = np.tanh(out["x0"].to_numpy(dtype=float) - 0.2 * actions + 0.1 * ids)
        out["done"] = 0
        out.loc[out.groupby("episode_id").tail(1).index, "done"] = 1
        return out


RLAdapter = ManifoldEnv


class StreamingGenerator(BaseAdapter):
    """UC6 streaming adapter with event-time metadata and batch iterator."""

    name = "streaming"
    schema = {"event_time": "int", "watermark": "int", "sequence_id": "int"}

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Add event-time and watermark fields.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Dataframe with streaming metadata.
        """

        out = frame.copy()
        base = 1_700_000_000
        out["sequence_id"] = np.arange(len(out))
        out["event_time"] = base + out["sequence_id"]
        out["watermark"] = out["event_time"] - rng.integers(0, 5, len(out))
        return out

    def batches(self, frame: pd.DataFrame, batch_size: int = 32) -> Iterator[pd.DataFrame]:
        """Yield dataframe batches.

        Args:
            frame: Stream dataframe.
            batch_size: Maximum rows per batch.

        Yields:
            Dataframe batches.
        """

        for start in range(0, len(frame), batch_size):
            yield frame.iloc[start : start + batch_size].copy()


StreamingAdapter = StreamingGenerator


class BenchmarkSuite(BaseAdapter):
    """UC7 supervised benchmark labels and algorithm grid metadata."""

    name = "benchmark"
    schema = {"label": "int", "difficulty": "float"}

    def apply(self, frame: pd.DataFrame, latent: Array, ids: Array, rng: np.random.Generator) -> pd.DataFrame:
        """Add labels and difficulty score.

        Args:
            frame: Input dataframe.
            latent: Latent matrix.
            ids: Manifold identifiers.
            rng: Local RNG.

        Returns:
            Dataframe with benchmark labels.
        """

        out = frame.copy()
        score = latent[:, 0] + 0.5 * latent[:, 1] + 0.1 * ids
        out["label"] = (score > np.median(score)).astype(int)
        out["difficulty"] = np.abs(score - np.median(score))
        return out

    @staticmethod
    def grid() -> pd.DataFrame:
        """Return default benchmark grid.

        Returns:
            Dataframe of benchmark scenarios.
        """

        rows = []
        for manifolds in [2, 3, 5]:
            for drift in [0.001, 0.005, 0.02]:
                rows.append({"scenario": f"K{manifolds}_drift{drift}", "manifolds": manifolds, "drift_scale": drift, "task": "classification"})
        return pd.DataFrame(rows)


