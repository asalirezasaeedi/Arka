        """Run lightweight runtime diagnostics.

        Args:
            config: Optional config used for reproducibility checks.

        Returns:
            Diagnostics dictionary.
        """

        cfg = config or GeneratorConfig(n_samples=32, episodes=1)
        return {"health": self.health().__dict__, "reproducibility": StatisticalMetrics.reproducibility_check(cfg)}

