def parser() -> argparse.ArgumentParser:
    """Create CLI parser.

    Returns:
        Configured argparse parser.
    """

    p = argparse.ArgumentParser(prog="dgp-plus-plus", description="DGP++ v3.0 Level-5 data generator")
    sub = p.add_subparsers(dest="cmd")

    def common(sp: argparse.ArgumentParser) -> None:
        sp.add_argument("--samples", type=int, default=240)
        sp.add_argument("--features", type=int, default=8)
        sp.add_argument("--latent-dim", type=int, default=8)
        sp.add_argument("--manifolds", type=int, default=3)
        sp.add_argument("--episodes", type=int, default=2)
        sp.add_argument("--drift-scale", type=float, default=0.005)
        sp.add_argument("--shock-rate", type=float, default=0.25)
        sp.add_argument("--noise", type=float, default=0.05)
        sp.add_argument("--coupling", type=float, default=1.0)
        sp.add_argument("--seed", type=int, default=42)
        sp.add_argument("--dashboard", action="store_true")

    g = sub.add_parser("generate", help="generate benchmark views")
    common(g)
    g.add_argument("--adapter", choices=["core"] + sorted(ADAPTERS), default="benchmark")
    g.add_argument("--output-dir", default="artifacts/outputs")
    g.add_argument("--formats", nargs="+", choices=["csv", "parquet"], default=["csv", "parquet"])
    g.set_defaults(func=cmd_generate)
    gate = sub.add_parser("gate0", help="run Gate-0 validation")
    common(gate)
    gate.set_defaults(func=cmd_gate0)
    v = sub.add_parser("validate", help="validate saved analysis file")
    v.add_argument("input")
    v.set_defaults(func=cmd_validate)
    a = sub.add_parser("adapters", help="list adapters")
    a.set_defaults(func=cmd_adapters)
    m = sub.add_parser("menu", help="show use-case menu")
    m.set_defaults(func=cmd_menu)
    doctor = sub.add_parser("doctor", help="run health checks")
    doctor.set_defaults(func=cmd_doctor)
    diag = sub.add_parser("diagnostics", help="run runtime diagnostics")
    common(diag)
    diag.set_defaults(func=cmd_diagnostics)
    cal = sub.add_parser("calibrate", help="run autonomous calibration")
    common(cal)
    cal.add_argument("--adapter", choices=["core"] + sorted(ADAPTERS), default="core")
    cal.add_argument("--max-iterations", type=int, default=5)
    cal.set_defaults(func=cmd_calibrate)
    exp = sub.add_parser("experiment", help="run repeated experiment")
    common(exp)
    exp.add_argument("--name", default="experiment")
    exp.add_argument("--adapter", choices=["core"] + sorted(ADAPTERS), default="benchmark")
    exp.add_argument("--repeats", type=int, default=3)
    exp.add_argument("--artifact-root", default="artifacts")
    exp.set_defaults(func=cmd_experiment)
    br = sub.add_parser("benchmark-run", help="run benchmark grid")
    br.add_argument("--artifact-root", default="artifacts")
    br.set_defaults(func=cmd_benchmark_run)
    met = sub.add_parser("metrics", help="print Prometheus metrics")
    common(met)
    met.add_argument("--adapter", choices=["core"] + sorted(ADAPTERS), default="benchmark")
    met.set_defaults(func=cmd_metrics)
    for name in ["anomaly", "drift", "causal", "federated", "rl", "stream", "benchmark"]:
        sp = sub.add_parser(name, help=f"run {name} use case")
        common(sp)
        sp.set_defaults(func=cmd_shortcut)
    return p


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Run CLI entry point.

    Args:
        argv: Optional argument vector.

    Returns:
        Process exit code.
    """

    p = parser()
    args = p.parse_args(argv)
    if not hasattr(args, "func"):
        return cmd_menu(args)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
